"""CPU gate for the block-shape experiment: one input per invocation, no GPU.

  CUDA_VISIBLE_DEVICES= python scripts/research_panel/shape_gate.py \
      --run RUN --source-labels LABELS --nnzflat-artifacts ROOT --task 0

Builds the real BOO object for every (method, k_r, k_c) from saved labels and records what
each shape costs before any GPU time is spent. See experiments/2026-11-06_block_shape/README.md.

Row labels come from the k_r labeling and column labels from the k_c labeling. Saved labels
(k32/64/128, all four methods) are hash-validated by bench_real.load_labels. k16 and k256 exist
only for identity and hem; they are computed here with the same settings and saved under RUN.

Traffic is per feature, for the block-encoded part of the matrix only:
  x_staged   sum_b n_c(b)          columns Step A loads today
  x_read     sum_b active_cols(b)  columns the block's nonzeros touch
  y_commits  sum_b active_rows(b)  rowseg's Y atomics (zero accumulators are skipped)
Balance is the rowseg thread mapping: per block the busiest group of G = T/(P/FPT) residue
classes of local rows, against ceil(nnz/G).
"""
import argparse
import json
import os
from pathlib import Path
import socket
import sys
import time

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / 'tests' / 'torch_fast_spdmm'), str(ROOT / 'torch_fast_spdmm'), str(ROOT)]

from benchmark import bench_real as br  # noqa: E402
from benchmark import nnzflat_common as nc  # noqa: E402
from benchmark import real_matrices as rm  # noqa: E402

SAVED_K = (32, 64, 128)
EXTRA_K = (16, 256)
METHODS = ('identity', 'hem', 'graclus', 'metis')
EXTRA_METHODS = ('identity', 'hem')
SHAPES = ((32, 32), (64, 32), (128, 32), (256, 32),
          (64, 64), (128, 64), (256, 64), (128, 128),
          (64, 16), (128, 16), (256, 16), (16, 16),
          (32, 64), (32, 128))   # last two: column-heavy negative controls
PS = (32, 64, 128)
THREADS = (128, 256, 512)
BALANCE = ((256, 64, 1), (256, 64, 2), (256, 64, 4), (512, 64, 2), (512, 64, 4), (256, 128, 4))
OPTIN = 101376
SMEM, DRIVER, THREADS_SM, MAX_CTA = 102400, 1024, 1536, 16


def host():
    return dict(node=socket.gethostname(), cpu_model=br.cpu_model(),
                cpus=len(os.sched_getaffinity(0)), slurm_job_id=os.environ.get('SLURM_JOB_ID'))


def tasks(source_labels):
    """(prefix, matrix key), real matrices first, then generated by size."""
    prefixes = sorted({p.name.split('__keep__')[0] for p in Path(source_labels).glob('*__keep__*.npz')})
    real = [p for p in prefixes if not p.startswith('generated__')]
    gen = sorted((p for p in prefixes if p.startswith('generated__')),
                 key=lambda p: (int(p.rsplit('_n', 1)[1]), p))
    return [(p, p.replace('__', '/', 1)) for p in real + gen]


def load_csr(key, cache):
    if key.startswith('generated/'):
        from benchmark.bench_clustering import load_matrix
        profile, size = key.split('/', 1)[1].rsplit('_n', 1)
        t0 = time.perf_counter()
        csr = load_matrix(int(size), profile, nc.SEED)
        return csr, dict(matrix_sha256=rm.matrix_hash(csr), generate_s=time.perf_counter() - t0)
    spec, = rm.resolve([key])
    return rm.load(spec, cache, 'keep')


def labels_for(key, prefix, csr, record, method, k, source_labels, run):
    expect = dict(matrix=key, matrix_sha256=record['matrix_sha256'], shape=csr.shape,
                  explicit_zeros='keep', method=method, k=k, seed=nc.SEED)
    name = f'{prefix}__keep__{method}_k{k}.npz'
    if k in SAVED_K:
        return br.load_labels(Path(source_labels) / name, **expect)
    path = Path(run) / 'labels' / name
    if not path.exists():
        from torch_fast_spdmm.clustering import cluster_axes
        path.parent.mkdir(parents=True, exist_ok=True)
        t0 = time.perf_counter()
        rows, cols = cluster_axes(csr, method=method, target_nr=k, target_nc=k, max_nr=k, max_nc=k,
                                  seed=nc.SEED, feasible_first=True)
        br.save_labels(path, rows, cols, feasible_first=True, host=host(),
                       cluster_ms=1000 * (time.perf_counter() - t0), **expect)
    return br.load_labels(path, **expect)


def thread_capacity(arena):
    """Threads per SM by launch width, from the occupancy model in boo.py."""
    if arena > OPTIN:
        return {t: 0 for t in THREADS}
    return {t: min(SMEM // (arena + DRIVER), THREADS_SM // t, MAX_CTA) * t for t in THREADS}


def shape_row(boo):
    s = nc.boo_structure(boo)
    row = {k: s.get(k) for k in ('num_blocks', 'total_nnz', 'compressed_nnz', 'remainder_nnz',
                                 'remainder_fraction', 'max_nr', 'max_nc', 'max_nnz_blk',
                                 'num_row_groups', 'num_col_groups', 'row_group_mean', 'col_group_mean',
                                 'nnz_per_block_mean', 'nnz_per_block_p50', 'nnz_per_block_p95',
                                 'row_nnz_in_block_p50', 'row_nnz_in_block_p95', 'empty_block_row_fraction')}
    nb = s['num_blocks']
    if not nb:
        return row, s
    rgp = np.diff(np.asarray(boo.row_grp_ptr, np.int64))
    cgp = np.diff(np.asarray(boo.col_grp_ptr, np.int64))
    nr = rgp[np.asarray(boo.blk_row_grp, np.int64)]
    nc_ = cgp[np.asarray(boo.blk_col_grp, np.int64)]
    nz = np.diff(np.asarray(boo.blk_nz_ptr, np.int64))
    idx = np.asarray(boo.nz_idx, dtype=np.uint16).astype(np.int64)
    shifts = np.asarray(boo.blk_shift).astype(np.int64)
    blk = np.repeat(np.arange(nb), nz)
    lr = idx >> shifts[blk]
    lc = idx & ((1 << shifts[blk]) - 1)

    x_read = np.unique(blk * (int(nc_.max()) + 1) + lc).size
    y_commits = np.unique(blk * (int(nr.max()) + 1) + lr).size
    row.update(x_staged=int(nc_.sum()), x_read=int(x_read), y_commits=int(y_commits),
               nz_p99=float(np.percentile(nz, 99)))

    for p in PS:
        arena = nc.arena_rowseg(boo, p)
        row[f'arena_p{p}'] = arena
        cap = thread_capacity(arena)
        for t in THREADS:
            row[f'threads_sm_p{p}_t{t}'] = cap[t]
        row[f'best_threads_sm_p{p}'] = max(cap.values())

    for t, p, fpt in BALANCE:
        g = max(t // (p // fpt), 1)
        work = np.bincount(blk * g + lr % g, minlength=nb * g).reshape(nb, g)
        busiest = work.max(axis=1)
        ideal = np.ceil(nz / g).astype(np.int64)
        tag = f't{t}_p{p}_f{fpt}'
        row[f'busiest_sum_{tag}'] = int(busiest.sum())
        row[f'balance_gain_{tag}'] = float(busiest.sum() / ideal.sum())
    return row, s


def check_against_nnzflat(boo_dir, input_name, labeling, row, boo):
    """A square shape must reproduce the structure recorded by the 2026-10-14 CPU job."""
    if boo_dir is None or input_name is None:
        return None
    path = Path(boo_dir) / f'{input_name}__{labeling}.json'
    if not path.exists():
        return None
    meta = json.loads(path.read_text())
    got = (nc.boo_digest(boo), row['num_blocks'], row['max_nnz_blk'], row['arena_p64'])
    want = (meta['boo_digest'], meta['structure']['num_blocks'], meta['structure']['max_nnz_blk'],
            meta['arenas']['p64']['rowseg'])
    if got != want:
        raise ValueError(f'{path}: rebuilt {got[1:]} differs from recorded {want[1:]}')
    return meta['boo_digest']


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--run', type=Path, required=True)
    ap.add_argument('--source-labels', type=Path, required=True)
    ap.add_argument('--nnzflat-artifacts', type=Path, default=None,
                    help='artifacts/boo directory of the 2026-10-14 run, for the square-shape check')
    ap.add_argument('--cache', type=Path, default=rm.default_cache())
    ap.add_argument('--task', type=int, default=int(os.environ.get('SLURM_ARRAY_TASK_ID', '0')))
    ap.add_argument('--list', action='store_true')
    a = ap.parse_args()
    all_tasks = tasks(a.source_labels)
    if a.list:
        for i, t in enumerate(all_tasks):
            print(i, t[1])
        return
    import torch
    if torch.cuda.is_available():
        raise SystemExit('The gate must run without a GPU (CUDA_VISIBLE_DEVICES=)')

    prefix, key = all_tasks[a.task]
    print(f'gate task {a.task}: {key}', flush=True)
    t_start = time.perf_counter()
    csr, record = load_csr(key, a.cache)
    known = {inp.key: inp for inp in nc.INPUTS.values()}
    inp = known.get(key)
    out_dir = a.run / 'gate'
    out_dir.mkdir(parents=True, exist_ok=True)

    rows, checks = [], []
    for method in METHODS:
        cache = {}

        def get(k):
            if k not in cache:
                cache[k] = labels_for(key, prefix, csr, record, method, k, a.source_labels, a.run)
            return cache[k]

        for kr, kc in SHAPES:
            if (kr not in SAVED_K or kc not in SAVED_K) and method not in EXTRA_METHODS:
                continue
            row_labels, _, prov_r = get(kr)
            _, col_labels, prov_c = get(kc)
            t0 = time.perf_counter()
            try:
                boo = nc.build_boo(csr, row_labels, col_labels)
            except Exception as exc:  # recorded, not rerouted (e.g. uint16 local-coordinate bound)
                rows.append(dict(matrix=key, method=method, kr=kr, kc=kc, status=f'unsupported: {exc}'))
                print(f'  {method} {kr}x{kc}: UNSUPPORTED {exc}', flush=True)
                continue
            build_ms = 1000 * (time.perf_counter() - t0)
            row, _ = shape_row(boo)
            row.update(matrix=key, rows=csr.shape[0], cols=csr.shape[1], method=method, kr=kr, kc=kc,
                       status='ok', build_ms=build_ms, row_label_sha256=prov_r['label_sha256'],
                       col_label_sha256=prov_c['label_sha256'], boo_digest=nc.boo_digest(boo))
            if kr == kc and inp is not None and method == inp.method:
                digest = check_against_nnzflat(a.nnzflat_artifacts, inp.name, f'{method}_k{kr}', row, boo)
                if digest:
                    checks.append(dict(method=method, k=kr, boo_digest=digest))
            rows.append(row)
            print(f"  {method} {kr}x{kc}: {row.get('num_blocks')} blocks, arena_p64 {row.get('arena_p64')}, "
                  f"x {row.get('x_staged')}/{row.get('x_read')}, y {row.get('y_commits')}, "
                  f"rem {row.get('remainder_fraction', 0):.3f}, {build_ms:.0f} ms", flush=True)
            del boo

    fields = sorted({k for r in rows for k in r})
    br_path = out_dir / f'{prefix}.csv'
    nc_write_csv(br_path, rows, fields)
    rm._write_json(out_dir / f'{prefix}.json',
                   dict(matrix=key, matrix_sha256=record['matrix_sha256'], square_checks=checks,
                        rows=csr.shape[0], cols=csr.shape[1], nnz=int(csr.nnz), host=host(),
                        seconds=time.perf_counter() - t_start))
    print(f'SHAPE_GATE_DONE {key} {len(rows)} rows, {len(checks)} square checks, '
          f'{time.perf_counter() - t_start:.1f} s', flush=True)


def nc_write_csv(path, rows, fields):
    import csv
    tmp = Path(path).with_suffix('.tmp')
    with open(tmp, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    tmp.replace(path)


if __name__ == '__main__':
    main()
